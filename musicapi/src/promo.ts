import { randomInt } from "node:crypto";
import { query, queryOne, type QueryFn } from "./db.js";
/**
 * Promo codes: generation, validation and redemption.
 *
 * Kept separate from the mail code because a code is a billing object — it is
 * validated by checkout and redeemed by the payment settlement path, whether or
 * not a mail ever mentioned it.
 */

/** Ambiguous characters removed: no O/0, I/1, so a code read off a screen works. */
const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

export function generatePromoCode(prefix = "CAMX", length = 6): string {
  let body = "";
  for (let i = 0; i < length; i += 1) {
    body += ALPHABET[randomInt(0, ALPHABET.length)];
  }
  return `${prefix}-${body}`;
}

export type PromoKind = "percent" | "credit_bonus";

export interface PromoCode {
  id: string;
  code: string;
  kind: PromoKind;
  value: number;
  user_id: string | null;
  max_redemptions: number;
  redeemed_count: number;
  expires_at: string | null;
  is_active: boolean;
}

/** The campaign-level recipe stored in `mail_campaigns.promo_preset`. */
export interface PromoPreset {
  kind: PromoKind;
  value: number;
  expiresDays: number;
}

export function coercePreset(value: unknown): PromoPreset | null {
  const raw = (value ?? {}) as Record<string, unknown>;
  const kind: PromoKind | null =
    raw.kind === "percent" ? "percent" : raw.kind === "credit_bonus" ? "credit_bonus" : null;
  if (!kind) return null;
  const numeric = Number(raw.value);
  if (!Number.isFinite(numeric) || numeric <= 0) return null;
  // A 100% discount cannot be charged by the gateway.
  const clamped = kind === "percent" ? Math.min(99, Math.floor(numeric)) : Math.floor(numeric);
  if (clamped <= 0) return null;
  const expiresDays = Number.isFinite(Number(raw.expiresDays))
    ? Math.max(1, Math.min(90, Math.floor(Number(raw.expiresDays))))
    : 7;
  return { kind, value: clamped, expiresDays };
}

export interface CreatePromoOptions {
  kind: PromoKind;
  value: number;
  userId?: string | null;
  maxRedemptions?: number;
  expiresDays?: number;
  campaignId?: string | null;
  note?: string | null;
}

/**
 * Insert a code, retrying on the (rare) collision with an existing code string.
 * Returns null only if every attempt collided, which in practice means the
 * table is full of codes in this namespace.
 */
export async function createPromoCode(opts: CreatePromoOptions): Promise<PromoCode | null> {
  for (let attempt = 0; attempt < 6; attempt += 1) {
    const code = generatePromoCode();
    const row = await queryOne<PromoCode>(
      `INSERT INTO promo_codes
         (code, kind, value, user_id, max_redemptions, expires_at, campaign_id, note)
       VALUES ($1, $2, $3, $4, $5,
               CASE WHEN $6::int > 0 THEN now() + ($6::int * interval '1 day') ELSE NULL END,
               $7, $8)
       ON CONFLICT (code) DO NOTHING
       RETURNING id, code, kind, value, user_id, max_redemptions, redeemed_count,
                 expires_at::text AS expires_at, is_active`,
      [
        code,
        opts.kind,
        opts.value,
        opts.userId ?? null,
        opts.maxRedemptions ?? 1,
        opts.expiresDays ?? 0,
        opts.campaignId ?? null,
        opts.note ?? null,
      ],
    );
    if (row) return row;
  }
  return null;
}

export function presetToCreateOptions(
  preset: PromoPreset,
  userId: string,
  campaignId: string | null,
): CreatePromoOptions {
  return {
    kind: preset.kind,
    value: preset.value,
    userId,
    maxRedemptions: 1,
    expiresDays: preset.expiresDays,
    campaignId,
    note: "Generated by a mail campaign",
  };
}

export interface PromoQuote {
  codeId: string;
  code: string;
  kind: PromoKind;
  value: number;
  /** Price after the discount, in the pack's currency. */
  amount: number;
  /** Credits granted after any bonus. */
  credits: number;
  /** Money taken off the listed price (0 for a bonus code). */
  discount: number;
}

export type PromoResult =
  | { ok: true; quote: PromoQuote }
  | { ok: false; error: string };

/**
 * Pure quote calculation, exported so the money arithmetic can be unit-tested
 * without a database.
 */
export function computePromoQuote(
  promo: PromoCode,
  price: number,
  credits: number,
): PromoResult {
  // NUMERIC comes back from pg as a string; coerce once so arithmetic is honest.
  const value = Number(promo.value) || 0;

  if (promo.kind === "percent") {
    const discount = Math.round(price * value) / 100;
    const amount = Math.round((price - discount) * 100) / 100;
    if (amount <= 0) {
      return { ok: false, error: "This code covers the full price; use a different pack." };
    }
    return {
      ok: true,
      quote: {
        codeId: promo.id,
        code: promo.code,
        kind: promo.kind,
        value,
        amount,
        credits,
        discount,
      },
    };
  }

  return {
    ok: true,
    quote: {
      codeId: promo.id,
      code: promo.code,
      kind: promo.kind,
      value,
      amount: price,
      credits: credits + Math.floor(value),
      discount: 0,
    },
  };
}

/**
 * Validate a code for one user and one pack.
 *
 * Every rejection is a distinct message on purpose: "already used" and "expired"
 * are what support actually needs to know, and a vague error generates a ticket.
 */
export async function validatePromoForUser(
  rawCode: string,
  userId: string,
  pack: { price: number; credits: number },
): Promise<PromoResult> {
  const code = rawCode.trim().toUpperCase();
  if (!code) return { ok: false, error: "Enter a promo code." };

  const promo = await queryOne<PromoCode>(
    `SELECT id, code, kind, value, user_id, max_redemptions, redeemed_count,
            expires_at::text AS expires_at, is_active
     FROM promo_codes WHERE code = $1`,
    [code],
  );
  if (!promo) return { ok: false, error: "That code does not exist." };
  if (!promo.is_active) return { ok: false, error: "That code is no longer active." };
  if (promo.user_id && promo.user_id !== userId) {
    // Deliberately identical to "does not exist": a targeted code must not
    // confirm that someone else's code is real.
    return { ok: false, error: "That code does not exist." };
  }
  if (promo.expires_at && new Date(promo.expires_at).getTime() < Date.now()) {
    return { ok: false, error: "That code has expired." };
  }
  if (promo.redeemed_count >= promo.max_redemptions) {
    return { ok: false, error: "That code has already been used." };
  }

  const already = await queryOne<{ id: string }>(
    "SELECT id FROM promo_redemptions WHERE code_id = $1 AND user_id = $2",
    [promo.id, userId],
  );
  if (already) return { ok: false, error: "You have already used that code." };

  return computePromoQuote(promo, pack.price, pack.credits);
}

/**
 * Record a redemption. Runs inside the payment transaction's `tx` so the credit
 * grant, the paid status and the redemption commit together. The unique
 * (code_id, user_id) index makes a retry a no-op instead of a double count.
 */
export async function redeemPromo(
  tx: QueryFn,
  args: {
    codeId: string;
    userId: string;
    paymentTransactionId: string;
    discount: number;
    creditsGranted: number;
  },
): Promise<void> {
  const inserted = await tx<{ id: string }>(
    `INSERT INTO promo_redemptions
       (code_id, user_id, payment_transaction_id, discount_amount, credits_granted)
     VALUES ($1, $2, $3, $4, $5)
     ON CONFLICT (code_id, user_id) DO NOTHING
     RETURNING id`,
    [args.codeId, args.userId, args.paymentTransactionId, args.discount, args.creditsGranted],
  );
  if (inserted.length === 0) return;
  await tx(
    "UPDATE promo_codes SET redeemed_count = redeemed_count + 1 WHERE id = $1",
    [args.codeId],
  );
}

export interface PromoSummaryRow {
  id: string;
  code: string;
  kind: PromoKind;
  value: number;
  user_id: string | null;
  redeemed_count: number;
  max_redemptions: number;
  expires_at: string | null;
  is_active: boolean;
  campaign_id: string | null;
  created_at: string;
}

export async function listPromoCodes(limit = 200): Promise<PromoSummaryRow[]> {
  return query<PromoSummaryRow>(
    `SELECT id, code, kind, value, user_id, redeemed_count, max_redemptions,
            expires_at::text AS expires_at, is_active, campaign_id, created_at
     FROM promo_codes
     ORDER BY created_at DESC
     LIMIT $1`,
    [limit],
  );
}
