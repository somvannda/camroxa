const SVG_NS = "http://www.w3.org/2000/svg";

export function icon(name: IconName, size = 16): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("fill", "currentColor");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.classList.add("icon-svg");
  const path = document.createElementNS(SVG_NS, "path");
  path.setAttribute("d", PATHS[name]);
  svg.append(path);
  return svg;
}

/**
 * Replaces every `<span data-icon="name">` placeholder with its SVG. Static
 * markup stays readable and the icons can be swapped without touching CSS.
 */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((element) => {
    const name = element.dataset.icon as IconName;
    if (!name || !PATHS[name]) return;
    const size = Number(element.dataset.iconSize ?? 16);
    element.replaceChildren(icon(name, Number.isFinite(size) ? size : 16));
  });
}
