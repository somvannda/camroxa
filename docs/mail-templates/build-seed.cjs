// Generates seed SQL for both stacks from the template files.
//
// Usage:
//   node docs/mail-templates/build-seed.cjs docs/mail-templates
//
// Writes seed-platform.sql (with send_mode) and seed-musicapi.sql (send_mode
// applied by migration 0036). Both are idempotent: re-running updates the body
// of an existing keyed template instead of duplicating it.

const fs = require("fs");
const path = require("path");

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node build-seed.cjs <templates-dir>");
  process.exit(1);
}

// key, file prefix, mode
const TEMPLATES = [
  ["welcome", "01", "auto"],
  ["never_generated", "02", "auto"],
  ["pack_ladder", "03", "manual"],
  ["discount", "04", "manual"],
  ["low_balance", "05", "auto"],
  ["winback", "06", "auto"],
  ["receipt", "07", "auto"],
  ["payment_expired", "08", "auto"],
  ["credits_expiring", "09", "auto"],
  ["referral", "10", "manual"],
  ["stems_spotlight", "11", "manual"],
  ["seasonal", "12", "manual"],
];

function sqlLiteral(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function extractVars(source) {
  const found = new Set();
  for (const m of source.matchAll(/\{\{\s*([a-zA-Z0-9_.]+)\s*\}\}/g)) found.add(m[1]);
  return [...found].sort();
}

const rows = [];

for (const [key, prefix, mode] of TEMPLATES) {
  const file = fs
    .readdirSync(dir)
    .filter((f) => f.startsWith(`${prefix}-`) && f.endsWith(".html"))
    .sort()[0];
  if (!file) {
    console.warn(`missing template ${prefix}-*.html, skipping ${key}`);
    continue;
  }
  const raw = fs.readFileSync(path.join(dir, file), "utf8");
  const subject =
    (raw.match(/<title>([\s\S]*?)<\/title>/i) || [, key])[1].trim().replace(/\s+/g, " ");
  const bodyMatch = raw.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  const html = (bodyMatch ? bodyMatch[1] : raw).trim();
  const vars = extractVars(html);
  rows.push({ key, file, subject, html, vars, mode });
}

function build(withSendMode) {
  const values = rows
    .map((r) => {
      const cols = [
        sqlLiteral(r.key),
        sqlLiteral("en"),
        sqlLiteral(r.key.replace(/_/g, " ")),
        sqlLiteral(r.subject),
        sqlLiteral(r.html),
        "NULL",
        `ARRAY[${r.vars.map(sqlLiteral).join(", ")}]::text[]`,
        withSendMode ? sqlLiteral(r.mode) : null,
      ].filter(Boolean);
      return `  (${cols.join(", ")})`;
    })
    .join(",\n");

  const columnList = withSendMode
    ? "(key, locale, name, subject, html, text, vars, send_mode)"
    : "(key, locale, name, subject, html, text, vars)";

  const updates = withSendMode
    ? `subject = EXCLUDED.subject, html = EXCLUDED.html, vars = EXCLUDED.vars,
       send_mode = EXCLUDED.send_mode, updated_at = now()`
    : `subject = EXCLUDED.subject, html = EXCLUDED.html, vars = EXCLUDED.vars,
       updated_at = now()`;

  return `-- Generated by build-seed.cjs from ${rows.length} template files.
-- Idempotent: re-running refreshes the body and variables of each key.

INSERT INTO mail_templates ${columnList}
VALUES
${values}
ON CONFLICT (key, locale) WHERE key IS NOT NULL DO UPDATE SET
  ${updates};
`;
}

// Both stacks carry send_mode: platform from migration 140, musicapi from 0036.
const platformPath = path.join(dir, "seed-platform.sql");
const musicapiPath = path.join(dir, "seed-musicapi.sql");
fs.writeFileSync(platformPath, build(true), "utf8");
fs.writeFileSync(
  musicapiPath,
  "-- Apply AFTER migration 0036_mail_send_mode.sql.\n" + build(true),
  "utf8",
);

console.log(`seeded ${rows.length} templates`);
for (const r of rows) {
  console.log(`  ${r.key.padEnd(18)} ${r.mode.padEnd(7)} ${String(r.html.length).padStart(6)} B  ${r.vars.length} vars`);
}
