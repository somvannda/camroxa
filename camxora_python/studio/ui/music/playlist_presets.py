PRESETS_BY_ID: dict[str, PlaylistPreset] = {p.id: p for p in PLAYLIST_PRESETS}


def colors_from_preset(preset: PlaylistPreset) -> dict[str, str]:
    return {
        "bg_from": preset.bg_from,
        "bg_to": preset.bg_to,
        "accent": preset.accent,
        "accent2": preset.accent2,
        "surface": preset.surface,
        "muted": preset.muted,
        "text": "#ffffff",
    }


def presets_for_category(category: str) -> tuple[PlaylistPreset, ...]:
    if category in ("all", "playlist"):
        return PLAYLIST_PRESETS
    return tuple(p for p in PLAYLIST_PRESETS if category in p.tags)
